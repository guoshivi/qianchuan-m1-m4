'use strict';
/**
 * roi-map.js — **保本ROI(Y) → 实投ROI目标** 的映射（**单一事实源**）
 *
 * 📌 现行规则（用户 2026-09-27 定，**两档**）：
 *    · **保本 < 5** ⇒ `目标ROI = 保本 × 0.7`（7/10 —— 低保本的计划给足空间，不然跑不起来）
 *    · **保本 ≥ 5** ⇒ `目标ROI = 保本 × 0.4`（4/10）
 *    （以前是"约一半或稍少、高值约 1/3"的分档表 ⇒ 已废）
 *    例：2.81 → 1.97 · 3.73 → 2.61 · 4.36 → 3.05 · 5.68 → 2.27 · 6.54 → 2.62 · 18.67 → 7.47（两位小数）
 *    ⚠️ 边界口径：**5 本身按 4/10**（"5 以下"按**不含 5** 处理）。要含 5 就把 `保本低档线` 改成 5.0000001 之类，
 *       一行的事 —— 但别偷偷改，先跟用户确认 ✗
 *
 * ⚠️ 历史坑（canon #22）：这张表原来**有两份实现** —— 本文件 + `bit-qc-lib.js` 里闭包内的一份 ✗
 *    ⇒ 现在 `bit-qc-lib.js` 已改为 `require('./roi-map.js')`，**只此一处** ✓
 *
 * ⚠️ 另一条更重要的口径（2026-09-27 用户要的「后期改过的 ROI 要能被认出来」）：
 *    重建时**优先用旧计划当前的 ROI 目标**（人后来在千川改过的那个），映射只当兜底 ⇒ 见 `resolveRoi()`
 */

/** 用户定的比例（两档）：保本 < 低档线 ⇒ 7/10；否则 ⇒ 4/10 */
const ROI_RATIO = 0.4;          // 保本 ≥ 5
const ROI_RATIO_LOW = 0.7;      // 保本 < 5（7/10）
const 保本低档线 = 5;            // ⚠️ 边界：**不含 5**（5 本身走 4/10）

const 取数 = (v) => parseFloat(String(v == null ? '' : v).replace(/[^0-9.]/g, '')) || 0;
const 两位 = (n) => Math.round(n * 100) / 100;

/**
 * 保本ROI → 实投ROI目标（现行规则：**保本 <5 ⇒ ×0.7；≥5 ⇒ ×0.4**，两位小数）
 * 入参为空/非数字时**原样返回**（与历史行为一致，别让调用方拿到 0 ✗）
 */
function mapRoi(baob) {
  const b = 取数(baob);
  if (!b) return baob;
  return 两位(b * (b < 保本低档线 ? ROI_RATIO_LOW : ROI_RATIO));
}

/**
 * ⚠️ **只用于识别**「这个 ROI 是旧规则给的」——**不再用于设置**（别再拿它当映射用 ✗）
 *   为什么要留：老计划的 ROI 大多是旧表算出来的（例 保本 6.54 → 2.2）。
 *   重建时如果无脑"沿用旧计划当前的目标"，那 **4/10 就永远生不效** ✗
 *   ⇒ 判据：**当前值 == 旧表值 ⇒ 那是旧规则的产物 ⇒ 换成 4/10**；
 *            **当前值 ≠ 旧表值 ⇒ 是人真改过的 ⇒ 认人家的** ✓（用户 2026-09-27 要的）
 */
const LEGACY_TABLE = [
  { max: 3.5, target: 1.59 }, { max: 4.5, target: 2 }, { max: 6, target: 2 },
  { max: 7.5, target: 2.2 }, { max: 9, target: 2.4 }, { max: 10, target: 3 },
  { max: 12, target: 3.2 }, { max: 15, target: 3.5 }, { max: Infinity, target: 4 },
];
function legacyMap(baob) {
  const b = 取数(baob);
  if (!b) return null;
  for (const r of LEGACY_TABLE) if (b <= r.max) return r.target;
  return 4;
}

/**
 * 重建时该用哪个 ROI 目标？—— **判据就这一处**（别在 m8 里再写一遍 ✗）
 *   ① 旧计划**当前**的 ROI 目标存在，且**不是旧规则给的** ⇒ 认它（人改过的 ✓）
 *   ② 当前值是旧规则给的（== 旧表值）⇒ 换成新口径 **保本 × 0.4**
 *   ③ 没有当前值 ⇒ 也走 ② 的映射
 *   ④ 连保本都没有 ⇒ 原样（调用方自己兜 '1.40'）
 * @returns {{值:string, 来源:string}}
 */
function resolveRoi(opt = {}) {
  // 🎯 人工覆盖（飞书 `🎯 重建用ROI` 手填）⇒ **直接认，跳过一切推断** ✓
  //    为什么必须绕过：人填的值**可能正好等于旧表值**（例：保本 5.68 填 2.0 = 旧表值 2 ✗）
  //    若还走"旧规则产物 ⇒ 换新口径"，就会把人**明确写的数**改掉 ✗✗（用户 2026-09-27 要的正是"认我改过的"）
  const 覆盖 = 取数(opt.人工覆盖);
  if (覆盖) return { 值: String(opt.人工覆盖).trim(), 来源: '飞书手填（人覆盖 ⇒ 直接认）' };
  const 目标 = 取数(opt.当前目标);
  // ✋ **手调的硬证据**（2026-09-27 用户：「手调的应该有优先级」）：
  //    计划名里的 `→X` 记录的是**我们建它时设的值** ✓ ⇒ 当前目标 ≠ 名字里的 X
  //    就说明**建完之后被改过**（人改的，或平台自动调优 ⇒ 两种都该认 ✓）—— 这是**证据**，不是猜 ✓
  //    比原来那个"当前值是否等于旧表值"的启发式可靠得多 ✓（那个遇到"人恰好填了旧表值"就误判 ✗）
  const 名字值 = 取数(opt.名字目标);
  if (目标 && 名字值 && Math.abs(目标 - 名字值) >= 0.005) {
    return { 值: String(opt.当前目标).trim(), 来源: '旧计划当前目标（名字记的是 ' + 名字值 + ' ⇒ 之后被改过 ⇒ 认它 ✋）' };
  }
  const 保本 = 取数(opt.保本);
  const 新值 = 保本 ? mapRoi(保本) : null;
  // ⚠️ 标签必须**跟着档位**：低档却说"映射(4/10)" ⇒ 日志/台账会撒谎 ✗（2026-09-27 自查抓到）
  const 档 = 保本 ? (保本 < 保本低档线 ? '7/10 低保本' : '4/10') : '';
  if (目标) {
    const 旧值 = 保本 ? legacyMap(保本) : null;
    const 是旧规则给的 = 旧值 != null && Math.abs(目标 - 旧值) < 0.005;
    if (是旧规则给的 && 新值 != null) {
      return { 值: String(新值), 来源: '映射(' + 档 + ')：旧值 ' + 目标 + ' 是旧规则给的 ⇒ 换新口径' };
    }
    return { 值: String(opt.当前目标).trim(), 来源: '旧计划当前目标（人改过 ⇒ 认它）' };
  }
  if (新值 != null) return { 值: String(新值), 来源: '映射(' + 档 + ')' };
  return { 值: String(opt.保本 == null ? '' : opt.保本), 来源: '原样' };
}

module.exports = { mapRoi, resolveRoi, legacyMap, ROI_RATIO, ROI_RATIO_LOW, 保本低档线, LEGACY_TABLE };
