/**
 * **弱截断词**：出现在中间时不一定该截 —— 只有当它**前面的主体够长**（≥4 汉字）才截。
 *
 * 踩过（2026-09-13 马桶垫品）：
 *   品名「小狗格纹靠背马桶垫家用卫生间防水坐便垫…」里最早的 CUT 词是「防水」，
 *   截出来是「小狗格纹靠背马桶垫家用卫生间」→ 再按 10 字符硬切 →
 *   **「小狗格纹靠背马桶垫家」**（末尾「家」是「家用」被切断的半截词，挂在商品卡上像错字）。
 *   把「家用」也列为截断词就正好切在它前面 → 「小狗格纹靠背马桶垫」。
 *
 * ⚠️ 但不能无条件截：品类词开头的品名（如「厨房家用收纳盒」）截在「家用」会只剩「厨房」。
 *   所以弱词要求 head ≥ 4 汉字；不够就走原来的"剥掉该词继续找"分支。
 */
const CUT_WEAK = ['家用'];

/** 只数汉字（用于"这段够不够成一个主体词"的语义判断，**不是**平台计数口径） */
function countHan(s) { return (String(s).match(/[\u4e00-\u9fa5]/g) || []).length; }

/** 数**字符**（码点）—— 这才是抖音短标题的计数口径（空格/标点/字母/数字都占额） */
function countChars(s) { return [...String(s)].length; }

/** 按汉字数截断（保留汉字 ≤ n）—— 语义辅助，**不是**平台计数器 */
function cutHan(s, n) {
  let out = '', c = 0;
  for (const ch of String(s)) {
    if (/[\u4e00-\u9fa5]/.test(ch)) {
      if (c >= n) break;
      c++;
    }
    out += ch;
  }
  return out;
}

/**
 * 收到 ≤ max **字符**（抖音硬上限），并尽量不切在词中间。
 *   · 已够短 → 原样返回（去掉首尾分隔符）
 *   · 超长 → 先按字符裁到 max，再**回退到最后一个分隔符处**（前段仍有 ≥2 汉字才认）
 * 踩过：只数汉字 → 空格漏算 → 上传到抖音才被拒（白跑一次上传 + 一次挂车）。
 */
/**
 * **只做修饰、不会收尾**的字：被硬切到"以它结尾"时，说明切在了词中间，回退一字。
 *   耐（耐抓/耐磨）· 防（防水/防滑）· 可（可爱/可折）· 不（不掉屑）· 免（免洗）· 超（超大）· 多（多功能）
 * ⛔ 不含 款/型/式/装 —— 它们**可以**收尾（升级款/加大型/便携式/超值装）。
 * 踩过（2026-09-13）：
 *   ① 马桶垫品名硬切出「小狗格纹靠背马桶垫**家**」（「家用」被切断）→ 由 CUT_WEAK 处理
 *   ② 猫抓板品名硬切出「白卡猫抓板猫窝一体**耐**」（「耐抓」被切断）→ 由这条通用规则处理
 */
const FRAGMENT_TAIL = /[耐防可不免超多]$/;

function fitChars(s, max = 10) {
  const out = String(s).replace(/^[\s\-_·]+|[\s\-_·]+$/g, '');
  if (countChars(out) <= max) return out;
  const 有截断 = true;                                   // 走到这里必然切过（原文 > max）
  const cut = [...out].slice(0, max).join('');
  const m = cut.match(/^(.*)[\s\-_·]+\S*$/);          // 贪婪：取最后一个分隔符
  // ⚠️ 2026-09-18：回退也不能退太狠 —— 「反光 宠物牵引绳外出狗绳…」回退到最后一个分隔符
  //    会只剩「反光」两个字（短标题等于废了）。要求回退后的 head ≥ max 的一半，否则用硬切结果。
  const 回退下限 = Math.max(4, Math.ceil(max / 2));
  const head = (m && countHan(m[1]) >= 2 && countChars(m[1].replace(/[\s\-_·]+$/, '')) >= 回退下限)
    ? m[1].replace(/[\s\-_·]+$/, '')
    : cut.replace(/[\s\-_·]+$/, '');
  // 尾部是"半截词"→ 回退一字（只剩 ≥4 字符才敢退，太短宁可留着）
  if (有截断 && FRAGMENT_TAIL.test(head) && countChars(head) > 4) {
    const back = [...head].slice(0, -1).join('').replace(/[\s\-_·]+$/, '');
    if (countHan(back) >= 2) return back;
  }
  return head;
}

/** 营销词（只用来判断**括号里那一段**是不是营销，正文里的"学生/宿舍"是真实描述不能误伤） */
const BRACKET_MARKETING = /必备|爆款|网红|推荐|特价|清仓|包邮|新款|升级|加厚|正品|官方|旗舰|同款|必入|好物|福利|热卖|限量|到手/;

/**
 * 括号里的**功能/卖点词**：不是商品名，整段丢掉（和营销词一样处理）。
 *   2026-09-18 实测两例：「【防挣脱】猫咪牵引绳…」「【反光】新款宠物牵引绳…」
 *   —— 不丢的话前者推成「防挣脱 猫咪牵引绳」，后者更糟：LEAD 剥掉「新款」后
 *   分隔符回退直接只剩「**反光**」（2 个字，短标题等于废了）。
 *   ⛔ 判据要求正文 ≥2 汉字（`【爆款】杯` 这种仍然原样保留），且**不按长度猜**
 *   （「【老树红心柚】」是商品名，必须留着 —— 所以只认词表，不认"短括号就丢"）。
 */
const BRACKET_FEATURE = /防挣脱|防爆冲|反光|防水|防滑|防尘|防霉|耐磨|耐咬|可拆洗|可机洗|免洗|除臭|去味/;

/**
 * 开头的【括号段】是营销词时，把它整段丢掉、只留正文。
 *   踩过（2026-09-13 吹风机品）：「【宿舍必备款】高速吹风机800W…」去掉括号后**首段正好是
 *   "宿舍必备款"**，而 `fitChars` 的"优先在分隔符处截断"就在那儿截 → 短标题变成纯营销词
 *   （挂到车上就废了；实测预览里真的出现了）。
 *   ⚠️ 只有"括号里像营销 **且** 正文还够"才丢；【老树红心柚】这种括号里就是商品名，必须保留。
 * @returns {string|null} 正文（要丢括号段时）；null = 不动
 */
function stripBracketMarketing(name) {
  const m = String(name || '').match(/^\s*[【\[（(「『]([^】\]）)」』]{2,20})[】\]）)」』]\s*(.+)$/);
  if (!m) return null;
  if (!BRACKET_MARKETING.test(m[1]) && !BRACKET_FEATURE.test(m[1])) return null;
  if (countHan(m[2]) < 2) return null;
  return m[2];
}

/** 规格/型号后缀（800W / 304 / 500ml / 12寸 …）—— 修饰不是主体，从它处截断 */
const SPEC_RE = /[0-9]+\s*(?:W|w|V|v|A|a|ml|ML|L|g|G|kg|KG|寸|米|cm|CM|mm|MM)/;

