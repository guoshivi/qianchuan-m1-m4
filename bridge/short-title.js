const FIXED_SHORT_TITLE = '视频同款';

function shortTitle(fullName, max = 10) {
  // 2026-09-29 起：一律「视频同款」✓（旧推导已停用 —— 见上面那段说明）
  return FIXED_SHORT_TITLE;
}

function _shortTitleLegacy(fullName, max = 10) {
  const 去括号营销 = stripBracketMarketing(fullName);
  let s = String(去括号营销 != null ? 去括号营销 : (fullName || ''))
    .replace(/\s+/g, ' ')
    .replace(/[【】\[\]（）()「」『』]/g, ' ')
    .trim();

  // ① 反复剥开头修饰
  let changed = true;
  while (changed) {
    changed = false;
    for (const re of LEAD) {
      const m = s.match(new RegExp('^' + re + '[\\s\\-_·]*'));
      if (m && m[0].length < s.length) { s = s.slice(m[0].length).trim(); changed = true; }
    }
  }

  // ② 从属性/功能词处截断：取最早命中的词。若它就在**开头**（如「不锈钢保温杯」），
  //    说明它是材质/属性前缀而不是主体后缀 → 剥掉它继续找，别把整串都截没。
  for (let guard = 0; guard < 8; guard++) {
    let cutAt = -1, cutWord = null;
    for (const w of CUT.concat(CUT_WEAK)) {
      const i = s.indexOf(w);
      if (i >= 0 && (cutAt < 0 || i < cutAt)) { cutAt = i; cutWord = w; }
    }
    if (cutAt < 0) break;
    const head = s.slice(0, cutAt).trim();
    const 需要长度 = CUT_WEAK.includes(cutWord) ? 4 : 2;   // 弱词（家用…）要前面主体够长才截
    if (countHan(head) >= 需要长度) { s = head; break; }
    s = (s.slice(0, cutAt) + ' ' + s.slice(cutAt + cutWord.length)).trim();
  }

  // ②b 规格/型号后缀处截断（800W / 500ml / 12寸…）—— "高速吹风机800W小功率…" → "高速吹风机"
  //    ⚠️ CUT 是 indexOf 纯字符串匹配，放不下正则，所以这里单独用 SPEC_RE 判一次。
  {
    const sp = s.match(SPEC_RE);
    if (sp && sp.index >= 2) {
      const head = s.slice(0, sp.index).trim();
      if (countHan(head) >= 2) s = head;
    }
  }

  // 兜底：剥/截之后没剩东西 → 退回原串
  if (countHan(s) < 2) s = String(fullName || '').replace(/\s+/g, ' ').trim();

  // ③ 按**字符数**截到 max（空格也占额），并优先切在分隔符处
  return fitChars(s, max);
}

/** 校验：给抖音输入框用，返回 {ok, 字符数, 汉字数, 值, max} */
function verify(value, max = 10) {
  const n = countChars(value), h = countHan(value);
  return { ok: n > 0 && n <= max, 字符数: n, 汉字数: h, 值: value, max };
}

module.exports = { shortTitle, shortTitleLegacy: _shortTitleLegacy, countHan, countChars, cutHan, fitChars, verify, LEAD, CUT, CUT_WEAK, FRAGMENT_TAIL, BRACKET_MARKETING, BRACKET_FEATURE };
